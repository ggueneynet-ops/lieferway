export function orderStatusLabel(locale: Locale, status: string, fulfillment?: string | null) {
  const pickup = fulfillment === "PICKUP";
  const t = dictionaries[locale] ?? dictionaries.de;
  if (pickup) {
    if (status === "PREPARING") return STATUS_LABEL[locale].ACCEPTED;
    if (status === "READY") return t.pickupStatusReady;
    if (status === "DELIVERED") return t.pickupStatusPickedUp;
  }
  return STATUS_LABEL[locale][status] ?? status;
}

